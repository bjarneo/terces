package rules

import (
	"bytes"
	"fmt"
	"regexp"
	"strings"

	"github.com/BurntSushi/toml"
	"go.yaml.in/yaml/v3"
)

// The gitleaks TOML format. Only the fields that the converter uses are listed.
type glConfig struct {
	Rules []glRule `toml:"rules"`
}

type glRule struct {
	ID          string    `toml:"id"`
	Description string    `toml:"description"`
	Regex       string    `toml:"regex"`
	SecretGroup int       `toml:"secretGroup"`
	Entropy     float64   `toml:"entropy"`
	Keywords    []string  `toml:"keywords"`
	Path        string    `toml:"path"`
	SkipReport  bool      `toml:"skipReport"`
	Allowlists  []glAllow `toml:"allowlists"`
	Allowlist   *glAllow  `toml:"allowlist"`
}

type glAllow struct {
	Description string   `toml:"description"`
	Condition   string   `toml:"condition"`
	RegexTarget string   `toml:"regexTarget"`
	Regexes     []string `toml:"regexes"`
	Stopwords   []string `toml:"stopwords"`
	Paths       []string `toml:"paths"`
	Commits     []string `toml:"commits"`
}

// ConvertOptions controls ConvertGitleaks.
type ConvertOptions struct {
	// Exclude lists rule IDs to leave out, such as rules that a local rule
	// file already covers.
	Exclude []string
}

// ConvertGitleaks converts a gitleaks TOML config to the terces YAML
// rule format. It returns the YAML document and one note for each rule that
// it did not convert.
func ConvertGitleaks(data []byte, opts ConvertOptions) ([]byte, []string, error) {
	var cfg glConfig
	if _, err := toml.Decode(string(data), &cfg); err != nil {
		return nil, nil, fmt.Errorf("parse gitleaks config: %w", err)
	}
	exclude := map[string]bool{}
	for _, id := range opts.Exclude {
		exclude[strings.TrimSpace(id)] = true
	}

	var out []Rule
	var notes []string
	for _, g := range cfg.Rules {
		switch {
		case exclude[g.ID]:
			notes = append(notes, fmt.Sprintf("%s: excluded", g.ID))
			continue
		case g.Regex == "":
			notes = append(notes, fmt.Sprintf("%s: skipped, the rule matches file paths only", g.ID))
			continue
		case g.SkipReport:
			notes = append(notes, fmt.Sprintf("%s: skipped, the rule is a helper for composite rules", g.ID))
			continue
		}
		if _, err := regexp.Compile(g.Regex); err != nil {
			notes = append(notes, fmt.Sprintf("%s: skipped, regex does not compile: %v", g.ID, err))
			continue
		}
		r := Rule{
			ID:          g.ID,
			Description: g.Description,
			Keywords:    g.Keywords,
			Regex:       g.Regex,
			SecretGroup: g.SecretGroup,
			EntropyMin:  g.Entropy,
			Severity:    severityFor(g.ID),
			Path:        g.Path,
		}
		allows := g.Allowlists
		if g.Allowlist != nil {
			allows = append(allows, *g.Allowlist)
		}
		for _, a := range allows {
			if len(a.Regexes) == 0 && len(a.Stopwords) == 0 && len(a.Paths) == 0 {
				// Commit allowlists refer to gitleaks' own history.
				continue
			}
			cond := strings.ToLower(a.Condition)
			if cond == "or" {
				cond = ""
			}
			target := a.RegexTarget
			if target == "secret" {
				target = ""
			}
			r.Allow = append(r.Allow, RuleAllow{
				Description: a.Description,
				Condition:   cond,
				RegexTarget: target,
				Regexes:     a.Regexes,
				Stopwords:   a.Stopwords,
				Paths:       a.Paths,
			})
		}
		out = append(out, r)
	}

	var buf bytes.Buffer
	buf.WriteString("# Generated by `terces rules import-gitleaks` from the gitleaks\n")
	buf.WriteString("# default config (config/gitleaks.toml). MIT license. See THIRD_PARTY.md.\n")
	buf.WriteString("# Do not edit this file by hand. Put local changes in a separate rule file.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(out); err != nil {
		return nil, nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, nil, err
	}
	return buf.Bytes(), notes, nil
}

func severityFor(id string) string {
	switch {
	case strings.Contains(id, "private-key"):
		return "critical"
	case strings.HasPrefix(id, "generic"):
		return "medium"
	default:
		return "high"
	}
}
