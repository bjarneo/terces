//go:embed report.html
var reportTemplate string

// Column is one column of an HTML table. Kind is "text", "code",
// "number" or "severity".
type Column struct {
	Name string `json:"name"`
	Kind string `json:"kind"`
}

// Card is one number at the top of an HTML report. Kind is empty or a
// severity, which sets the color.
type Card struct {
	Label string `json:"label"`
	Value int    `json:"value"`
	Kind  string `json:"kind,omitempty"`
}

// Breakdown is a small table of counts in an HTML report.
type Breakdown struct {
	Title string  `json:"title"`
	Rows  []Count `json:"rows"`
}

// HTMLGaps is the table of blobs that the scan did not read in full.
type HTMLGaps struct {
	Title   string     `json:"title"`
	Text    string     `json:"text"`
	Columns []string   `json:"columns"`
	Rows    [][]string `json:"rows"`
}

// HTMLReport is the content of one HTML page. The page is one file with
// no external resources. Its script shows the data with textContent only.
type HTMLReport struct {
	Title       string      `json:"title"`
	Subtitle    string      `json:"subtitle"`
	Footer      string      `json:"footer"`
	Empty       string      `json:"empty"`
	Cards       []Card      `json:"cards"`
	Breakdowns  []Breakdown `json:"breakdowns"`
	Notices     []string    `json:"notices"`
	Columns     []Column    `json:"columns"`
	Rows        [][]string  `json:"rows"`
	Gaps        *HTMLGaps   `json:"gaps,omitempty"`
	SummaryOnly bool        `json:"summaryOnly"`
}

// WriteHTML writes the report as one HTML page.
func WriteHTML(w io.Writer, r *HTMLReport) error {
	if r.Footer == "" {
		r.Footer = "Generated by terces at " + time.Now().UTC().Format("2006-01-02 15:04 UTC") +
			". The report holds previews and fingerprints, never a full secret."
	}
	// json.Marshal escapes <, > and &, so the data cannot end the script
	// element. The page parses the JSON and sets text, never HTML.
	data, err := json.Marshal(r)
	if err != nil {
		return err
	}
	page := strings.Replace(reportTemplate, "__TITLE__", html.EscapeString(r.Title), 1)
	page = strings.Replace(page, "__DATA__", string(data), 1)
	_, err = io.WriteString(w, page)
	return err
}

// ReportOptions controls the Markdown and HTML reports of a scan.
type ReportOptions struct {
	// SummaryOnly leaves out the table of findings.
	SummaryOnly bool
	// Target names what the scan covered, such as a path or acme/api.
	Target string
}

// FindingsHTML writes scan findings as an HTML report.
func FindingsHTML(w io.Writer, groups []RepoFindings, st *scanner.Stats, opts ReportOptions) error {
	sum := Summarize(groups, st)
	r := &HTMLReport{
		Title:       "terces scan report",
		Empty:       "No findings.",
		SummaryOnly: opts.SummaryOnly,
	}
	if opts.Target != "" {
		r.Title = "terces scan: " + safetext.Display(opts.Target)
	}
	r.Subtitle = fmt.Sprintf("%d finding%s, %d different secret%s. Each finding can be a live secret. Revoke it first, then remove it from the code.",
		sum.Findings, plural(sum.Findings), sum.Secrets, plural(sum.Secrets))
	r.Cards = append(r.Cards, Card{Label: "findings", Value: sum.Findings}, Card{Label: "secrets", Value: sum.Secrets})
	for _, sev := range severities {
		r.Cards = append(r.Cards, Card{Label: sev, Value: sum.BySeverity[sev], Kind: sev})
	}
	if sum.Gaps > 0 {
		r.Cards = append(r.Cards, Card{Label: "not scanned in full", Value: sum.Gaps})
	}
	r.Breakdowns = []Breakdown{{"Top rules", sum.ByRule}, {"Top repositories", displayCounts(sum.ByRepo)}}
	withRepo := len(sum.ByRepo) > 0
	// A directory scan has no commits, so it gets no commit columns.
	withCommit := false
	for _, g := range groups {
		for _, f := range g.Findings {
			withCommit = withCommit || f.CommitSHA != ""
		}
	}
	if withRepo {
		r.Columns = append(r.Columns, Column{"Repository", "code"})
	}
	r.Columns = append(r.Columns, Column{"Severity", "severity"}, Column{"Rule", "code"}, Column{"Preview", "code"}, Column{"Location", "code"})
	if withCommit {
		r.Columns = append(r.Columns, Column{"Commit", "code"}, Column{"Introduced", "text"})
	}
	r.Columns = append(r.Columns, Column{"Fingerprint", "code"})
	for _, g := range groups {
		for _, f := range g.Findings {
			loc := safetext.Display(f.Path) + ":" + strconv.Itoa(f.Line)
			if f.Decoded != "" {
				loc += " (" + f.Decoded + ")"
			}
			date := f.CommittedAt
			if len(date) >= 10 {
				date = date[:10]
			}
			row := []string{f.Severity.String(), f.RuleID, safetext.Display(f.Preview), loc}
			if withCommit {
				row = append(row, shortSHA(f.CommitSHA), date)
			}
			row = append(row, fingerprint.Short(f.Fingerprint))
			if withRepo {
				row = append([]string{g.Repo}, row...)
			}
			r.Rows = append(r.Rows, row)
		}
	}
	if st != nil {
		for _, msg := range st.Warnings {
			r.Notices = append(r.Notices, "Warning: "+safetext.Inline(msg))
		}
		if len(st.Gaps) > 0 {
			gaps := &HTMLGaps{
				Title:   fmt.Sprintf("%d blob%s not scanned in full", sum.Gaps, plural(sum.Gaps)),
				Text:    "A blob above the size limit gets no scan. In a blob at the match limit, a rule found more secrets than the report shows.",
				Columns: []string{"Path", "Blob", "Reason", "Size"},
			}
			for _, g := range st.Gaps {
				size := ""
				if g.Size > 0 {
					size = strconv.FormatInt(g.Size, 10)
				}
				gaps.Rows = append(gaps.Rows, []string{safetext.Display(g.Path), g.Blob, g.Reason, size})
			}
			r.Gaps = gaps
		}
		r.Footer = "Scan: " + st.Summary() + ". Generated by terces at " + time.Now().UTC().Format("2006-01-02 15:04 UTC") +
			". The report holds previews and fingerprints, never a full secret."
	}
	return WriteHTML(w, r)
}

func displayCounts(cs []Count) []Count {
	out := make([]Count, len(cs))
	for i, c := range cs {
		out[i] = Count{safetext.Display(c.Name), c.Count}
	}
	return out
}

func shortSHA(sha string) string {
	if len(sha) > 12 {
		return sha[:12]
	}
	return sha
}
